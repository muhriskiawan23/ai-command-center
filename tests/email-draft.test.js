import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import vm from "node:vm";
const context={window:{}};
vm.runInNewContext(readFileSync(new URL("../public/email-draft.js",import.meta.url),"utf8"),context);
const build=context.window.BOREmailDraft.buildPrompt;
test("requires an email purpose",()=>assert.equal(build({}).ok,false));
test("builds structured prompt and no-send instruction",()=>{const r=build({recipient:"Tim",purpose:"Mengatur jadwal rapat",points:"Kamis pagi",tone:"ramah"});assert.equal(r.ok,true);assert.match(r.prompt,/Penerima: Tim/);assert.match(r.prompt,/Tujuan\/konteks: Mengatur jadwal rapat/);assert.match(r.prompt,/Nada: ramah/);assert.match(r.prompt,/Jangan mengirim email/);});
test("bounds user-provided fields and marks them as data",()=>{const r=build({purpose:"x".repeat(2000),subject:"y".repeat(300)});assert.ok(r.prompt.length<4000);assert.match(r.prompt,/Semua nilai pada bagian DATA/);});